const dns = require("dns");
try { dns.setDefaultResultOrder("ipv4first"); } catch (e) {}
require("dotenv").config({ path: ".env.local" });
const db = require("../src/db");
const storage = require("../src/storage");
const auth = require("../src/auth");
const realtime = require("../src/realtime");

async function runTests() {
  console.log("====================================================");
  console.log("TESTING ALL NEON SERVICES & APPLICATION END-TO-END");
  console.log("====================================================\n");

  let passed = 0;
  let failed = 0;

  function assert(condition, message) {
    if (condition) {
      console.log(`  ✓ PASS: ${message}`);
      passed++;
    } else {
      console.error(`  ❌ FAIL: ${message}`);
      failed++;
    }
  }

  // ----------------------------------------------------
  // TEST 1: Neon Lakebase Postgres
  // ----------------------------------------------------
  console.log("[TEST 1/4] Neon Lakebase Postgres...");
  try {
    const aliveRes = await db.query("SELECT current_database(), current_user, version()");
    assert(aliveRes.rows.length > 0, `Database connected: DB '${aliveRes.rows[0].current_database}' as user '${aliveRes.rows[0].current_user}'`);

    // Test inserting a book
    const testBook = await db.createBook({
      title: "Test Publication — Automated Verification",
      author: "Maryam Irekeola, PhD",
      category: "Test Category",
      description: "End-to-end service verification item",
      cover_url: "assets/img/maryam-avatar.jpg",
      pdf_url: "https://storage.neon.tech/assets/test.pdf",
      pdf_key: "test-pdf-key.pdf",
      page_count: 5,
    });
    assert(testBook && testBook.id, `Created book record (ID: ${testBook.id}) in Postgres`);

    // Test querying the book
    const queriedBook = await db.getBookById(testBook.id);
    assert(queriedBook && queriedBook.title === testBook.title, `Queried book record by ID from Postgres`);

    // Clean up test book
    await db.deleteBook(testBook.id);
    assert(true, `Cleaned up test record from Postgres`);
  } catch (err) {
    assert(false, `Postgres test failed: ${err.message}`);
  }

  // ----------------------------------------------------
  // TEST 2: Neon Object Storage (S3) & Text-to-PDF
  // ----------------------------------------------------
  console.log("\n[TEST 2/4] Neon Object Storage & Branded Text-to-PDF...");
  try {
    // Compile PDF from text
    const textSample = "Executive Summary\n\nThis is an automated test document generated by Maryam Irekeola's library system to verify Neon Object Storage integration.\n\nKey Outcomes:\n- Document generation succeeds.\n- Formatting and branding verified.\n- Stored in Neon S3 bucket.";
    const pdfResult = await storage.generateBrandedPdf({
      title: "Automated Verification Report",
      author: "Maryam Irekeola, PhD",
      category: "Verification",
      text: textSample,
    });
    assert(pdfResult.buffer && pdfResult.buffer.length > 1000, `Generated branded PDF (${pdfResult.buffer.length} bytes, ${pdfResult.pageCount} page(s))`);

    // Upload to Neon S3
    const testKey = `test/automated-test-${Date.now()}.pdf`;
    const uploadRes = await storage.uploadToStorage(pdfResult.buffer, testKey, "application/pdf");
    assert(uploadRes.publicUrl && uploadRes.publicUrl.includes(testKey), `Uploaded PDF to Neon Object Storage bucket '${uploadRes.bucket}'`);
    console.log(`    File URL: ${uploadRes.publicUrl}`);
  } catch (err) {
    assert(false, `Object Storage test failed: ${err.message}`);
  }

  // ----------------------------------------------------
  // TEST 3: Neon Auth & Admin Authentication
  // ----------------------------------------------------
  console.log("\n[TEST 3/4] Neon Auth & Admin Authentication...");
  try {
    // Verify Neon Auth JWKS
    assert(process.env.NEON_AUTH_JWKS_URL, `Neon Auth JWKS URL configured: ${process.env.NEON_AUTH_JWKS_URL}`);
    const jwksRes = await fetch(process.env.NEON_AUTH_JWKS_URL);
    assert(jwksRes.status === 200, `Neon Auth JWKS endpoint reachable (HTTP 200)`);

    // Verify Admin login
    const loginRes = await auth.loginAdmin("admin", "admin123");
    assert(loginRes.token && loginRes.user, `Admin login successful. JWT issued for user '${loginRes.user.username}'`);

    // Verify token
    const verified = auth.verifyToken(loginRes.token);
    assert(verified && verified.username === "admin", `JWT token successfully verified with signature`);
  } catch (err) {
    assert(false, `Auth test failed: ${err.message}`);
  }

  // ----------------------------------------------------
  // TEST 4: Neon Realtime
  // ----------------------------------------------------
  console.log("\n[TEST 4/6] Neon Realtime...");
  try {
    assert(process.env.NEON_REALTIME_URL, `Neon Realtime URL configured: ${process.env.NEON_REALTIME_URL}`);
    assert(process.env.NEON_REALTIME_SECRET, `Neon Realtime Secret configured`);

    const rtConfig = realtime.getRealtimeConfig();
    assert(rtConfig.active, `Realtime broadcast engine active`);

    // Broadcast test event
    realtime.broadcastEvent("SYSTEM_TEST", { test: true });
    assert(true, `Broadcasted Realtime event to live stream`);
  } catch (err) {
    assert(false, `Realtime test failed: ${err.message}`);
  }

  // ----------------------------------------------------
  // TEST 5: Category Management
  // ----------------------------------------------------
  console.log("\n[TEST 5/6] Category Management...");
  try {
    const testCatName = `TestCat-${Date.now()}`;
    const newCat = await db.createCategory(testCatName);
    assert(newCat && newCat.name === testCatName, `Created category '${testCatName}'`);

    const allCats = await db.getAllCategories();
    assert(allCats.some(c => c.name === testCatName), `Retrieved categories list containing new category`);

    const delCat = await db.deleteCategory(newCat.id);
    assert(delCat && delCat.id === newCat.id, `Deleted category '${testCatName}'`);
  } catch (err) {
    assert(false, `Category management test failed: ${err.message}`);
  }

  // ----------------------------------------------------
  // TEST 7: Blog Posts CRUD
  // ----------------------------------------------------
  console.log("\n[TEST 7/8] Blog Posts CRUD on Neon Lakebase...");
  try {
    // 1. Create blog
    const newBlog = await db.createBlog({
      title: "Automated Test Blog Post",
      author: "Maryam Irekeola, PhD",
      category: "Research Guides",
      excerpt: "Testing automated blog creation and storage on Neon Lakebase Postgres.",
      content: "<p>This is test content for verification.</p>",
      cover_url: "assets/img/maryam-avatar.jpg",
      published: true,
    });
    assert(newBlog && newBlog.id, `Created blog post record (ID: ${newBlog.id})`);

    // 2. Query blog
    const fetchedBlog = await db.getBlogById(newBlog.id);
    assert(fetchedBlog && fetchedBlog.title === "Automated Test Blog Post", `Retrieved blog post by ID`);

    // 3. Update blog
    const updatedBlog = await db.updateBlog(newBlog.id, {
      title: "Updated Test Blog Post Title",
      category: "Policy Briefs",
    });
    assert(updatedBlog && updatedBlog.title === "Updated Test Blog Post Title" && updatedBlog.category === "Policy Briefs", `Updated blog post title & category`);

    // 4. Delete blog
    const delBlog = await db.deleteBlog(newBlog.id);
    assert(delBlog && delBlog.id === newBlog.id, `Deleted blog post record`);
  } catch (err) {
    assert(false, `Blog posts CRUD test failed: ${err.message}`);
  }

  // ----------------------------------------------------
  // TEST 8: Category Deletion Tag Consistency
  // ----------------------------------------------------
  console.log("\n[TEST 8/8] Category Deletion Tag Consistency (No Orphaned Tags)...");
  try {
    // 1. Create temporary category
    const tempCatName = `TempToDelete-${Date.now()}`;
    const tempCat = await db.createCategory(tempCatName);
    assert(tempCat && tempCat.id, `Created temporary category '${tempCatName}'`);

    // 2. Create a book and a blog assigned to this category
    const bookWithCat = await db.createBook({
      title: "Book In Temp Category",
      author: "Maryam Irekeola, PhD",
      category: tempCatName,
      description: "Testing category deletion cleanup",
      cover_url: "assets/img/maryam-avatar.jpg",
      pdf_url: "https://storage.neon.tech/assets/test.pdf",
      page_count: 2,
    });

    const blogWithCat = await db.createBlog({
      title: "Blog In Temp Category",
      author: "Maryam Irekeola, PhD",
      category: tempCatName,
      excerpt: "Testing category deletion cleanup",
      content: "<p>Blog content</p>",
      published: true,
    });
    assert(bookWithCat.category === tempCatName && blogWithCat.category === tempCatName, `Assigned book and blog to '${tempCatName}'`);

    // 3. Delete the category
    await db.deleteCategory(tempCat.id);

    // 4. Verify book and blog category were automatically updated to 'General'
    const refreshedBook = await db.getBookById(bookWithCat.id);
    const refreshedBlog = await db.getBlogById(blogWithCat.id);
    assert(refreshedBook.category === "General", `Book category safely updated from '${tempCatName}' to 'General'`);
    assert(refreshedBlog.category === "General", `Blog category safely updated from '${tempCatName}' to 'General'`);

    // Clean up test book and blog
    await db.deleteBook(bookWithCat.id);
    await db.deleteBlog(blogWithCat.id);
  } catch (err) {
    assert(false, `Category deletion tag consistency test failed: ${err.message}`);
  }

  // Summary
  console.log("\n====================================================");
  console.log(`TEST RESULTS: ${passed} passed, ${failed} failed.`);
  console.log("====================================================");

  if (failed > 0) {
    process.exit(1);
  }
}

if (require.main === module) {
  runTests()
    .then(() => process.exit(0))
    .catch((err) => {
      console.error("Test runner crashed:", err);
      process.exit(1);
    });
}

module.exports = { runTests };
